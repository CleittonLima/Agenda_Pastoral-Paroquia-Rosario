// Busca um tema pelo id — cai no tema padrão ("Jesus Cristo") se não encontrar
export function encontrarTema(id) {
  return TEMAS.find(t => t.id === id) || TEMAS[0];
}

// Lista os temas de uma categoria, na ordem em que foram cadastrados
export function temasDaCategoria(categoriaId) {
  return TEMAS.filter(t => t.categoria === categoriaId);
}
